Deendoon ("the app") is a debt-collection management tool used by a single
Business Owner per business account (tenant). This policy explains what
information the app handles and how.

Information We Collect
Deendoon stores the business data you enter directly: customer records,
debts, payments, collection cases, reminders, and any documents or
attachments you upload. We do not collect this information from any
source other than what you or your team enter into the app.

How We Use Your Information
Your data is used only to provide the app's core features — tracking
debts, recording payments, scheduling reminders, and generating
statements, receipts, and other documents for your own business. Deendoon
does not use your business data for advertising, and the app does not
include any third-party analytics or advertising software.

Who Can See Your Data
Your business data is isolated to your account (tenant) and is never
visible to other Business Owners. The one exception is the Professional
Collection feature: if you explicitly submit a collection case for
professional recovery, the details you submit (along with your
declaration) become visible to Deendoon's Recovery Team review process
for that request only.

Data Storage and Security
Your data is stored on Deendoon's backend servers and protected using
industry-standard authentication and access controls. Access to your
account requires your login credentials, and administrative access is
restricted by role.

Data Retention
We retain your business data for as long as your account remains active.

Changes to This Policy
We may update this Privacy Policy as the app evolves. Continued use of
the app after an update means you accept the revised policy.

Contact
Questions about this policy can be sent through Contact Support in the
app once that channel is available.
